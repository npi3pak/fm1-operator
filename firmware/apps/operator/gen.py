"""OPERATOR's generated header: the read-only preset bank (presets/bank.txt, or the list in $OP_BANK) -> GEN_DIR/op_bank.h"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools"))
import oppreset  # noqa: E402


def main(gen):
    listing = Path(os.environ.get("OP_BANK", ROOT / "presets" / "bank.txt"))
    names = [ln.strip() for ln in listing.read_text().splitlines() if ln.strip() and not ln.startswith("#")]
    patches = [oppreset.load(listing.parent / n) for n in names]
    issues = [f"{n}: {i}" for n, p in zip(names, patches) for i in oppreset.problems(p)]
    if issues:
        raise SystemExit("presets: " + "; ".join(issues))
    text = "\n".join([
        "/* generated by firmware/apps/operator/gen.py from presets/bank.txt: do not edit */",
        "#pragma once",
        f"#define OP_BANK_N {len(patches)}u",
        "static const fm_patch_t OP_INIT = " + oppreset.c_patch(oppreset.INIT) + ";",
        "static const fm_patch_t OP_BANK[OP_BANK_N] = {",
        ",\n".join("    " + oppreset.c_patch(p) for p in patches),
        "};",
        "",
    ])
    out = Path(gen) / "op_bank.h"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f"presets: {len(patches)} in the bank")


if __name__ == "__main__":
    main(sys.argv[1])
